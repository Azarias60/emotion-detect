"""Identity application 使用的出站端口。"""

from typing import Protocol


class UserRepository(Protocol):
    def create(self, username: str, password_hash: str, created_at: str) -> int: ...
    def get_by_username(self, username: str): ...
    def get_by_id(self, user_id: int): ...
    def update_profile(self, user_id: int, values: dict, updated_at: str): ...
    def update_password(self, user_id: int, password_hash: str, updated_at: str): ...
    def increment_token_version(self, user_id: int) -> None: ...

