"""Reporting 的出站端口。"""
from typing import Protocol


class ReportRepository(Protocol):
    """报告存取 SQL 契约；行携带 create_user_id/result_json 等原始列。"""

    def list_reports(self, owner_id) -> list: ...
    def get_report(self, owner_id, report_id): ...
    def get_report_by_id(self, report_id): ...
    def insert_report(self, owner_id, report_type, result_json, now: str) -> dict: ...
    def update_facts(self, report_id, facts: dict, now: str, owner_id=None): ...
    def delete_report(self, owner_id, report_id) -> int: ...
